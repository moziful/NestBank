import { NextResponse } from 'next/server';
import { getSession, hasRole, hashPassword } from '@/lib/auth';
import { getDb } from '@/lib/mongodb';

// GET /api/admin/staff - list staff members with search, filters, pagination, and sorting
export async function GET(request) {
    try {
        const session = await getSession(request);
        if (!session || !hasRole(session, ['Admin'])) {
            return NextResponse.json({ success: false, message: 'Forbidden: Admin access required' }, { status: 403 });
        }

        const { searchParams } = new URL(request.url);
        const search = (searchParams.get('search') || '').trim();
        const role = searchParams.get('role');
        const department = searchParams.get('department');
        const status = searchParams.get('status');
        const sortBy = searchParams.get('sortBy') || 'createdAt';
        const sortOrder = searchParams.get('sortOrder') === 'asc' ? 1 : -1;
        const page = parseInt(searchParams.get('page') || '1', 10);
        const limit = parseInt(searchParams.get('limit') || '10', 10);

        const db = await getDb();
        const query = { role: 'Bank Staff' };

        if (search) {
            query.$or = [
                { name: { $regex: search, $options: 'i' } },
                { email: { $regex: search, $options: 'i' } },
                { employeeId: { $regex: search, $options: 'i' } },
                { phone: { $regex: search, $options: 'i' } },
            ];
        }

        if (department && department !== 'All') {
            query.department = department;
        }

        if (status && status !== 'All') {
            query.status = status;
        }

        const total = await db.collection('users').countDocuments(query);
        const staffList = await db.collection('users')
            .find(query, { projection: { password: 0, transactionPin: 0 } })
            .sort({ [sortBy]: sortOrder })
            .skip((page - 1) * limit)
            .limit(limit)
            .toArray();

        return NextResponse.json({
            success: true,
            staff: staffList,
            pagination: {
                total,
                page,
                limit,
                totalPages: Math.ceil(total / limit),
            },
        });
    } catch (error) {
        console.error('Fetch staff error:', error);
        return NextResponse.json({ success: false, message: 'Internal server error' }, { status: 500 });
    }
}

// POST /api/admin/staff - add new staff account with autogenerated employee ID & audit log
export async function POST(request) {
    try {
        const session = await getSession(request);
        if (!session || !hasRole(session, ['Admin'])) {
            return NextResponse.json({ success: false, message: 'Forbidden: Admin access required' }, { status: 403 });
        }

        const body = await request.json();
        const {
            name,
            email,
            phone,
            department,
            designation,
            password,
            status = 'Active',
            joiningDate,
        } = body;

        if (!name || !email || !password || !department || !designation) {
            return NextResponse.json(
                { success: false, message: 'Name, email, password, department, and designation are required.' },
                { status: 400 }
            );
        }

        const db = await getDb();
        const existing = await db.collection('users').findOne({ email: email.trim().toLowerCase() });
        if (existing) {
            return NextResponse.json(
                { success: false, message: 'An employee with this email already exists.' },
                { status: 409 }
            );
        }

        // Generate next employee ID (e.g. STF-1007)
        const staffCount = await db.collection('users').countDocuments({ role: 'Bank Staff' });
        const employeeId = `STF-${1000 + staffCount + 1}`;

        const hashedPassword = await hashPassword(password);
        const username = email.split('@')[0].toLowerCase().replace(/[^a-z0-9]/g, '');

        const newStaff = {
            name: name.trim(),
            username,
            email: email.trim().toLowerCase(),
            phone: phone || '',
            employeeId,
            department,
            designation,
            role: 'Bank Staff', // Strictly BANK_STAFF (preventing privilege escalation)
            status, // Active, Inactive, Suspended
            password: hashedPassword,
            joiningDate: joiningDate ? new Date(joiningDate) : new Date(),
            createdBy: session.userId,
            createdAt: new Date(),
            updatedAt: new Date(),
        };

        const result = await db.collection('users').insertOne(newStaff);

        // Record creation in audit log
        await db.collection('auditLogs').insertOne({
            actorId: session.userId,
            actor: session.name || 'System Admin',
            action: 'STAFF_ACCOUNT_CREATED',
            event: `Created new staff account for ${newStaff.name} (${newStaff.employeeId}) in ${newStaff.department}`,
            recordRef: newStaff.employeeId,
            severity: 'Info',
            createdAt: new Date(),
        });

        return NextResponse.json({
            success: true,
            message: 'Staff account created successfully',
            staff: {
                id: result.insertedId.toString(),
                employeeId,
                name: newStaff.name,
                email: newStaff.email,
                role: newStaff.role,
                department: newStaff.department,
                status: newStaff.status,
            },
        }, { status: 201 });
    } catch (error) {
        console.error('Create staff error:', error);
        return NextResponse.json({ success: false, message: 'Internal server error' }, { status: 500 });
    }
}
